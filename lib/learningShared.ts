/**
 * Names shared by the learning loop's server code (lib/learning.ts), the API
 * routes and the page. Pure constants: safe to import in the browser.
 */

/** What a person did to the AI's work. Written to the Feedback tab as is. */
export const FEEDBACK_KIND = {
  fixOne: "Sửa 1 ảnh",
  fixSet: "Sửa cả bộ",
  redoOne: "Gen lại 1 ảnh (không ghi lý do)",
  redoSet: "Gen lại cả bộ (không ghi lý do)",
  relocalize: "Localize lại",
  approve: "Duyệt bản nháp",
} as const;
export type FeedbackKind = (typeof FEEDBACK_KIND)[keyof typeof FEEDBACK_KIND];

/** Kinds that mean the AI got an image wrong (counted in the correction rate). */
export const IMAGE_FIX_KINDS: string[] = [FEEDBACK_KIND.fixOne, FEEDBACK_KIND.fixSet, FEEDBACK_KIND.redoOne, FEEDBACK_KIND.redoSet];
/** Every kind that is a correction (approvals are not). */
export const CORRECTION_KINDS: string[] = [...IMAGE_FIX_KINDS, FEEDBACK_KIND.relocalize];

/** Which prompt an approved lesson is added to. Stored by key in the BaiHoc tab. */
export const LESSON_TARGETS = {
  anh: "Ảnh (prompt vẽ ảnh nền)",
  brief: "Brief (chữ trên banner, màu, nhân vật)",
  chu: "Chữ khi localize",
  adcopy: "Ad copy (headline, description)",
} as const;
export type LessonTarget = keyof typeof LESSON_TARGETS;
export const isLessonTarget = (v: unknown): v is LessonTarget => typeof v === "string" && v in LESSON_TARGETS;

export const LESSON_STATUS = { pending: "Chờ duyệt", applied: "Áp dụng", dropped: "Bỏ" } as const;
export type LessonStatus = (typeof LESSON_STATUS)[keyof typeof LESSON_STATUS];
export const isLessonStatus = (v: unknown): v is LessonStatus =>
  v === LESSON_STATUS.pending || v === LESSON_STATUS.applied || v === LESSON_STATUS.dropped;

export interface Lesson {
  id: string;
  proposedAt: string;
  target: LessonTarget;
  text: string;
  evidence: string;
  status: LessonStatus;
  reviewer: string;
  reviewedAt: string;
}

export interface QualityRow {
  version: string;
  /** Banner images generated (web + chat), errors excluded. */
  images: number;
  /** Image corrections: fixed or regenerated by a person. */
  imageFixes: number;
  /** imageFixes per 100 images. */
  per100: number | null;
  relocalize: number;
  approvals: number;
}

export interface FeedbackRow {
  time: string;
  email: string;
  tool: string;
  kind: string;
  app: string;
  markets: string;
  slot: string;
  reason: string;
  version: string;
}
